#!/usr/bin/env python3
"""Regenerate audit/stage16-implementation.json from the current tree.

The manifest lists the SHA-256 of every comparison source file (both
argument crates, the payload and harness crates, the workspace manifests,
the driver scripts, the guest ELFs and the vendored-source manifests), an
aggregate fingerprint over them, and the fingerprints of the vendored
open-magnetar patch and Flock sources.

The script is idempotent: running it twice on the same tree writes the same
bytes. `captured_on` changes only when some file hash changes. Run it last,
after every source change, then rebuild ram-compare, which embeds the
manifest in each report. scripts/check_stage16.py fails whenever the
manifest no longer matches the tree.
"""

import datetime
import hashlib
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MANIFEST = ROOT / "audit/stage16-implementation.json"
IMPLEMENTATION = "typed-spice-vs-twist-gf128-v5"

# Directories whose tracked and untracked (non-ignored) files are listed.
TREES = [
    "crates/ram-argument",
    "crates/ram-compare",
    "crates/ram-payload",
    "crates/spice-argument",
    "scripts",
    "payloads/open-magnetar",
]
# Single files listed when present.
FILES = [
    "Cargo.toml",
    "Cargo.lock",
    "audit/spice-masked-permutation-probe.py",
    "docs/methodology.md",
    "vendor/open-magnetar/UPSTREAM.json",
    "vendor/flock-boolean/UPSTREAM.json",
    "vendor/flock-boolean/check_provenance.py",
    "vendor/lean-grandproduct/UPSTREAM.json",
    "vendor/lean-grandproduct/Cargo.toml",
    "vendor/lean-grandproduct/LICENSE-APACHE",
    "vendor/lean-grandproduct/LICENSE-MIT",
    "vendor/lean-grandproduct/src/lib.rs",
    "vendor/lean-grandproduct/src/tests.rs",
]
SKIP_SUFFIXES = (".pyc",)


def fingerprint(hashes):
    """Same aggregate as scripts/check_spice_port.py."""
    result = hashlib.sha256()
    for name, value in sorted(hashes.items()):
        result.update(name.encode() + b"\0")
        result.update(bytes.fromhex(value))
    return result.hexdigest()


def sha256(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def listed_files(root=ROOT):
    names = set()
    output = subprocess.run(
        ["git", "ls-files", "--cached", "--others", "--exclude-standard", "-z", "--", *TREES],
        cwd=root,
        capture_output=True,
        check=True,
    ).stdout.decode()
    names.update(n for n in output.split("\0") if n)
    names.update(FILES)
    return sorted(
        n
        for n in names
        if (root / n).is_file()
        and "__pycache__" not in Path(n).parts
        and not n.endswith(SKIP_SUFFIXES)
    )


def collect(root=ROOT):
    """Manifest content for the current tree, without `captured_on`."""
    files = {name: sha256(root / name) for name in listed_files(root)}
    om = json.loads((root / "vendor/open-magnetar/UPSTREAM.json").read_text())
    flock = json.loads((root / "vendor/flock-boolean/UPSTREAM.json").read_text())
    return {
        "implementation": IMPLEMENTATION,
        "files_sha256": files,
        "source_sha256": fingerprint(files),
        "open_magnetar_patch_sha256": om["local_patch_sha256"],
        "flock_boolean_source_sha256": fingerprint(
            {**flock["source_sha256"], **flock["local_sha256"]}
        ),
        "note": (
            "Regenerated by scripts/write_manifest.py from the working tree. "
            "Result schema 5: interleaved rounds with paired bootstrap ratio "
            "intervals, verifier spans, structural proof sizes, composed "
            "soundness terms, load averages and host metadata. "
            "scripts/check_stage16.py requires every hash to match the tree."
        ),
    }


def render(manifest):
    return json.dumps(manifest, indent=2, sort_keys=False) + "\n"


def main():
    manifest = collect()
    captured_on = datetime.date.today().isoformat()
    if MANIFEST.exists():
        old = json.loads(MANIFEST.read_text())
        if old.get("files_sha256") == manifest["files_sha256"] and "captured_on" in old:
            captured_on = old["captured_on"]
    ordered = {"implementation": manifest.pop("implementation"), "captured_on": captured_on}
    ordered.update(manifest)
    text = render(ordered)
    changed = not MANIFEST.exists() or MANIFEST.read_text() != text
    MANIFEST.write_text(text)
    print(
        f"{'Wrote' if changed else 'Unchanged'} {MANIFEST.relative_to(ROOT)}: "
        f"{len(ordered['files_sha256'])} files, source {ordered['source_sha256']}"
    )


if __name__ == "__main__":
    try:
        main()
    except (KeyError, OSError, subprocess.CalledProcessError) as error:
        raise SystemExit(str(error)) from error
    sys.exit(0)
